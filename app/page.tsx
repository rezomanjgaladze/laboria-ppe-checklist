type InspectionResult = {
  percent: number;
  status: string;
};

type SavedInspection = {
  id: number;
  company: string;
  site: string;
  inspector: string;
  inspectionDate: string;
  answers: Record<string, string>;
  risk: Record<string, string>;
  result: InspectionResult;
  savedAt: string;
};

type AiFailedInspectionItem = {
  section: string;
  item: string;
  answer: string;
  risk: string;
  comments?: string;
};

type AiSafetyInsightPayload = {
  checklistType: string;
  reportType: string;
  companyName: string;
  siteLocation: string;
  inspector: string;
  inspectionDate: string;
  complianceScore: number;
  complianceStatus: string;
  riskCounts: {
    high: number;
    medium: number;
    low: number;
  };
  failedItems: AiFailedInspectionItem[];
  comments: string[];
  answeredItems: number;
  totalItems: number;
};

const ICON_MAP: Record<string, LucideIcon> = {
  ppe: ShieldCheck,
  emergency: HeartPulse,
  ergonomics: Cpu,
  dust: Wind,
  noise: Volume2,
  chemical: FlaskConical,
  machinery: HardHat,
  fire: Flame,
  electrical: Zap,
  general: Building2,
};

const getHistoryStorageKey = (checklistId: string) =>
  `laboria_${checklistId}_history`;

const readHistoryForChecklist = (checklistId: string): SavedInspection[] => {
  if (typeof window === "undefined") {
    return [];
  }

  try {
    const existing = window.localStorage.getItem(
      getHistoryStorageKey(checklistId),
    );

    return existing ? (JSON.parse(existing) as SavedInspection[]) : [];
  } catch {
    return [];
  }
};

